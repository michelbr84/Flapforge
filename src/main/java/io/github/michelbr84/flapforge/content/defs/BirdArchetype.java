package io.github.michelbr84.flapforge.content.defs;

/**
 * The seven bird archetypes of the roster (D30). The archetype drives the procedural silhouette
 * and groups birds in the selection screen; it carries no stats of its own.
 */
public enum BirdArchetype {

    /** Forgewing: the upstream feel, no modifiers. */
    BALANCED,
    /** Zephyr: light and fast. */
    SWIFT,
    /** Anvil: heavy, low terminal velocity. */
    HEAVY,
    /** Ironbeak: innate shield, reduced coin gain. */
    GUARDIAN,
    /** Jackdaw: high risk, high reward. */
    GAMBLER,
    /** Oracle: ability focused, an extra passive slot. */
    MYSTIC,
    /** Cinder: scales with owned upgrades. */
    FORGE
}
