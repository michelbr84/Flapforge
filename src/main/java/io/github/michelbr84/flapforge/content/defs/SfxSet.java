/**
 * The synthesised sound set of a world (E31.g), consumed by {@code ToneSynth} from M7.
 */
public enum SfxSet {

    /** Green Fields: soft, bright tones. */
    FIELDS,
    /** Wind Valley: airy, wide tones. */
    CANYON,
    /** Iron Forge: metallic, percussive tones. */
    FACTORY,
    /** Storm Sky: sharp, noisy tones. */
    STORM,
    /** The Void: hollow, detuned tones. */
    VOID
}
